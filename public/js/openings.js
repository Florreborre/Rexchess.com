const clean = (s) => s.replace(/[+#]/g, '');

// Antal inledande drag som följer boken, samt namnet på den längsta matchande öppningen.
export function matchOpening(sans) {
  const game = sans.map(clean);
  let plies = 0, name = null, nameLen = 0;
  for (const o of OPENINGS) {
    let i = 0;
    while (i < o.moves.length && i < game.length && clean(o.moves[i]) === game[i]) i++;
    if (i > plies) plies = i;
    if (i === o.moves.length && i > nameLen) { name = o.name; nameLen = i; }
    else if (i > nameLen && i >= 3) { name = o.name; nameLen = i; }
  }
  return { plies, name };
}
